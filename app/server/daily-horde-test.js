test('a locked daily countdown survives a ruleset request; Horde clears daily state after cancellation', () => {
	const hub = new Hub(() => {});
	hub.addPlayer(1, 'Host'); hub.addPlayer(2, 'Hero');
	hub.handle(1, { t: 'create', hero: 'witch', mode: 'lunch' });
	const room = hub.players.get(1).room;
	hub.handle(2, { t: 'join', code: room.code, hero: 'witch' });
	room.handle(1, { t: 'daily', enabled: true });
	assert.equal(hub.scheduleStart(room, 1, Date.now() + 60_000), true);
	const locked = room.daily, startsAt = room.startsAt;
	room.handle(1, { t: 'ruleset', id: 'horde' });
	assert.equal(room.ruleset, 'pve'); assert.equal(room.startsAt, startsAt);
	assert.equal(room.daily, locked, 'the advertised daily contract stays locked');
	assert.equal(room.cancelStart(), true);
	room.handle(1, { t: 'ruleset', id: 'horde' });
	room.handle(1, { t: 'daily', enabled: true });
	assert.equal(room.ruleset, 'horde'); assert.equal(room.dailySelected, false);
	assert.equal(room.daily, null); assert.equal(room.lobbyMsg().daily, null);
	room.start();
	assert.equal(room.startMsg().daily, null); assert.equal(room.swarm, null);
	assert.equal(room.heroes.get(2).maxHp, HEROES.witch.hp);
	assert.equal(room.heroes.get(2).mods.speedMul, 1);
	room.time = 20; room.finish(false, 0, 'wipe');
	assert.equal(room.overMsg.daily, null); assert.equal(room.lastLog.daily, null);
	assert.ok(room.overMsg.stats.every(row => !('ach' in row) && !('tot' in row)));
	room.toLobby(); room.setRuleset('pve'); room.start();
	assert.equal(room.daily, null); assert.equal(room.heroes.size, 2);
	assert.equal(room.heroes.get(1).mods.speedMul, 1, 'ordinary PvE does not inherit a daily modifier');
});

test('daily full/delta/recovery snapshots retain Swarm, caravan and movement acknowledgements together', () => {
	const frames = [], room = new Room('FIELDS', (pid, msg, json) => { if (msg.t === 's') frames.push(JSON.parse(json)); });
	room.addPlayer(1, 'Player', 'witch'); room.handle(1, { t: 'daily', enabled: true });
	let day = Date.UTC(2026, 10, 14);
	while (dailyFor(day).id !== 'swarm') day += 86_400_000;
	room.lockDaily(day); room.start();
	const cohort = room.swarm.cohorts[0], h = room.heroes.get(1);
	room.time = cohort.at + 1; cohort.spawned = 10; cohort.killed = 7;
	h.posAck = 13; h.moveEpoch = 2;
	room.caravan = { status: 'guarded', x: 1200, y: 0, killed: 0, total: 12, expires: room.time + 30 };
	const expected = room.snapshot(), decoder = new SnapshotDecoder();
	assert.equal(frames.at(-1).K, 1);
	let decoded = decoder.decode(frames.at(-1));
	assert.deepEqual(decoded.swarm, expected.swarm); assert.deepEqual(decoded.cv, expected.cv);
	assert.deepEqual(decoded.pa, [[1, 13, 2]]);
	room.time += .1; cohort.killed++; room.snapshot();
	assert.notEqual(frames.at(-1).K, 1, 'the next frame exercises the delta path');
	decoded = decoder.decode(frames.at(-1));
	assert.equal(decoded.swarm.killed, 8); assert.deepEqual(decoded.pa, [[1, 13, 2]]);
	const locked = room.daily; room.resync(1); room.snapshot();
	assert.equal(frames.at(-1).K, 1, 'reconnect requests a fresh key');
	decoded = new SnapshotDecoder().decode(frames.at(-1));
	assert.equal(room.daily, locked); assert.equal(decoded.swarm.killed, 8);
	assert.deepEqual(decoded.cv, expected.cv); assert.deepEqual(decoded.pa, [[1, 13, 2]]);
});

test('legacy PvE, Horde and every daily record version remain separate after restart', t => {
	const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'daily-horde-records-'));
	t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
	const store = new RunStore(); store.persist(dir);
	const row = (id, extra = {}) => ({ id, at: new Date().toISOString(), mode: 'lunch', team: [], summary: [], win: true, time: 60, ...extra });
	store.add(row('PV0001'), ['111']);
	store.add(row('HO0001', { ruleset: 'horde', ranked: false, directorWin: false }), ['111']);
	for (const version of [1, 2, 3, 4, 5]) store.add(row(`DA000${version}`, { daily: { ...dailyFor(), version, mode: 'lunch', players: 1 } }), ['111']);
	const restored = new RunStore(); restored.persist(dir);
	const history = restored.history('111');
	assert.deepEqual(history.mine.map(row => row.id).sort(), ['HO0001', 'PV0001']);
	assert.equal(history.mine.find(row => row.id === 'HO0001').ruleset, 'horde');
	assert.equal(history.mine.find(row => row.id === 'PV0001').ruleset, 'pve');
	assert.deepEqual(history.daily.best.map(row => row.daily.version).sort(), [1, 2, 3, 4, 5]);
	assert.equal(history.daily.mine.length, 5);
});
